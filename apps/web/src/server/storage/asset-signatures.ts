interface AssetSignature {
  extension: string;
  contentType: string;
  matches: (bytes: Uint8Array) => boolean;
}

const SIGNATURES: AssetSignature[] = [
  {
    extension: '.jpg',
    contentType: 'image/jpeg',
    matches: (b) => b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff,
  },
  {
    extension: '.png',
    contentType: 'image/png',
    matches: (b) =>
      b.length >= 8 &&
      b[0] === 0x89 &&
      b[1] === 0x50 &&
      b[2] === 0x4e &&
      b[3] === 0x47 &&
      b[4] === 0x0d &&
      b[5] === 0x0a &&
      b[6] === 0x1a &&
      b[7] === 0x0a,
  },
  {
    extension: '.gif',
    contentType: 'image/gif',
    matches: (b) =>
      b.length >= 6 &&
      b[0] === 0x47 &&
      b[1] === 0x49 &&
      b[2] === 0x46 &&
      b[3] === 0x38 &&
      (b[4] === 0x37 || b[4] === 0x39) &&
      b[5] === 0x61,
  },
  {
    extension: '.webp',
    contentType: 'image/webp',
    matches: (b) =>
      b.length >= 12 &&
      b[0] === 0x52 &&
      b[1] === 0x49 &&
      b[2] === 0x46 &&
      b[3] === 0x46 &&
      b[8] === 0x57 &&
      b[9] === 0x45 &&
      b[10] === 0x42 &&
      b[11] === 0x50,
  },
  {
    extension: '.mp4',
    contentType: 'video/mp4',
    matches: (b) =>
      b.length >= 12 && b[4] === 0x66 && b[5] === 0x74 && b[6] === 0x79 && b[7] === 0x70,
  },
  {
    extension: '.webm',
    contentType: 'video/webm',
    matches: (b) =>
      b.length >= 4 && b[0] === 0x1a && b[1] === 0x45 && b[2] === 0xdf && b[3] === 0xa3,
  },
];

export function detectAssetSignature(
  bytes: Uint8Array,
): { extension: string; contentType: string } | null {
  const match = SIGNATURES.find((signature) => signature.matches(bytes));
  return match ? { extension: match.extension, contentType: match.contentType } : null;
}
